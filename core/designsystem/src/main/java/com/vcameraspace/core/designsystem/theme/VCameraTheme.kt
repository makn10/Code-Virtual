val VCameraShapes = Shapes(
    extraSmall = RoundedCornerShape(6.dp),
    small = RoundedCornerShape(10.dp),
    medium = RoundedCornerShape(16.dp),
    large = RoundedCornerShape(22.dp),
    extraLarge = RoundedCornerShape(28.dp)
)

object VCameraTheme {
    val extendedColors: VCameraExtendedColors
        @Composable
        @ReadOnlyComposable
        get() = LocalVCameraExtendedColors.current

    val monoFontFamily: FontFamily
        @Composable
        @ReadOnlyComposable
        get() = LocalMonoFontFamily.current
}

@Composable
fun VCameraSpaceTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    typography: Typography = buildVCameraTypography(),
    monoFontFamily: FontFamily = FontFamily.Monospace,
    content: @Composable () -> Unit
) {
    val colorScheme = if (darkTheme) VCameraDarkColorScheme else VCameraLightColorScheme
    val extendedColors = if (darkTheme) DarkExtendedColors else LightExtendedColors

    CompositionLocalProvider(
        LocalVCameraExtendedColors provides extendedColors,
        LocalMonoFontFamily provides monoFontFamily
    ) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = typography,
            shapes = VCameraShapes,
            content = content
        )
    }
}
